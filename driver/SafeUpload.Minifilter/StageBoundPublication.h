C_ASSERT(sizeof(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW) == 2112);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, TemporaryIdentity) == 1944);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, CreateInformation) == 2000);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, Flags) == 2008);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, CreateStatus) == 2016);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, CleanupOperationId) == 2056);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_ROW, Reserved) == 2088);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_PAGE, Rows) == 64);
C_ASSERT(sizeof(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_PAGE) == 16960);
