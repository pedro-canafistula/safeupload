C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REQUEST, Flags) == 280);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REQUEST, InspectedDigest) == 288);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REQUEST, DestinationLeaf) == 320);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REQUEST, TemporaryLeaf) == 832);
C_ASSERT(sizeof(SAFEUPLOAD_BOUND_PUBLICATION_REPLY) == 128);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REPLY, DestinationGeneration) == 96);
C_ASSERT(FIELD_OFFSET(SAFEUPLOAD_BOUND_PUBLICATION_REPLY, Result) == 120);
C_ASSERT(sizeof(SAFEUPLOAD_BOUND_PUBLICATION_FACTS_REQUEST) == 64);
